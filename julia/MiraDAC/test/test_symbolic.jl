# compare_vectors of test_symbolic.cc: absolute, then relative error.
function compare_vectors(want, got, eps)
    length(want) == length(got) || return false
    for (p, q) in zip(got, want)
        d = abs(p - q)
        d > eps && (d /= abs(q) + 1e-300)
        d <= eps || return false
    end
    return true
end

# Every full_length coefficient of an NDA.
fullcoeffs(v::NDA) = (c = coeffs(v); [c; zeros(MiraDAC.env(v).full_length - length(c))])

@testset "symbolic (test_symbolic.cc)" begin
    @testset "SDA functions" begin
        # Order 5, 2 variables; f = sx + base[0]*base[0] + sy*base[1].
        init!(5, 2, 400; table=true)
        sx, sy = SymExpr("x"), SymExpr("y")
        b1, b2 = davar(1), davar(2)
        f = sx + b1 * b1 + sy * b2
        ev(sv) = fullcoeffs(evaluate(sv, Dict(sx => X, sy => Y)))

        for (fn, ref) in ((sqrt, V_SQRT), (exp, V_EXP), (log, V_LOG), (v -> v^3, V_POW3),
                          (v -> v^0.43, V_POW043), (erf, V_ERF), (sin, V_SIN), (cos, V_COS),
                          (tan, V_TAN), (sinh, V_SINH), (cosh, V_COSH), (tanh, V_TANH))
            @test compare_vectors(ref, ev(fn(f)), REF_EPS)
        end
        @test compare_vectors(V_ATAN, ev(atan(sx - 1 + b1 * b1 + sy * b2)), REF_EPS)
        @test compare_vectors(V_DER, ev(der(exp(f), 1)), REF_EPS)
        @test compare_vectors(V_INT, ev(integ(exp(f), 1)), REF_EPS)
        @test compare_vectors(V_SUBC, ev(substitute(exp(f), 1, 1.0)), REF_EPS)
        @test compare_vectors(V_SUB, ev(substitute(exp(f), 1, sqrt(f))), REF_EPS)
        @test compare_vectors(V_SUBV, ev(substitute(exp(f), [1, 2], [sqrt(f), sin(f)])), REF_EPS)

        slv = SDAList([sqrt(f), exp(f)])
        slx = SDAList([f, sin(f), cos(f)])
        for sly in (substitute(slx, [1, 2], slv), compose(slx, slv))
            for (sv, ref) in zip(sly, (V_VSUB0, V_VSUB1, V_VSUB2))
                @test compare_vectors(ref, ev(sv), REF_EPS)
            end
        end

        vals = compose([sqrt(f), sin(f), cos(f)], [X, Y])
        @test vals isa Vector{SymExpr}
        @test compare_vectors(V_COMPC, [Float64(MiraDAC.subs(e, Dict(sx => X, sy => Y))) for e in vals],
                              REF_EPS)
        clear!()
    end

    @testset "SDA interop" begin
        init!(4, 2, 400; table=true)
        b1, b2 = davar(1), davar(2)

        n = 1.5 + 2.0 * b1 + 3.0 * b2 + 0.5 * b1 * b2
        @test maximum(abs, fullcoeffs(n) - fullcoeffs(evaluate(promote_sda(n), Dict{SymExpr,Float64}()))) < SYM_EPS

        n = 1.0 + 2.0 * b1 + 0.5 * b2
        sx = SymExpr("x")
        s = sx + b1 * b1 + b2
        r1 = evaluate(n * s, Dict(sx => 1.0))
        r2 = evaluate(promote_sda(n) * s, Dict(sx => 1.0))
        @test maximum(abs, fullcoeffs(r1) - fullcoeffs(r2)) < SYM_EPS

        px, py = SymExpr("px"), SymExpr("py")
        @test abs(con(evaluate(px + py * b1 + b2, Dict(px => 2.0, py => 3.0))) - 2.0) < SYM_EPS
        qx = SymExpr("qx")
        @test abs(coeffs(evaluate(qx * b1 + 1.0 * b2, Dict(qx => 3.0)))[2] - 3.0) < SYM_EPS

        n_main = 1.0 + b1
        s_main = SymExpr("zz") + b2
        @test n_main * s_main isa SDA                       # same env: no error
        clear!()
        init!(4, 2, 400; table=true)
        @test_throws EnvError n_main * s_main
    end
    init!(4, 3, 400)
end
