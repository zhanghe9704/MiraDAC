def compare_vectors(a, b, eps):
    """compare_vectors of test_symbolic.cc: absolute, then relative error."""
    assert len(a) == len(b)
    for i, (p, q) in enumerate(zip(a, b)):
        d = abs(p - q)
        if d > eps:
            d /= abs(q) + 1e-300
        assert d <= eps, (i, p, q, d)
    return True


@pytest.fixture
def sym():
    """The SDA FUNCTIONS setup: order 5, 2 variables; returns (sx, sy, f) with
    f = sx + base[0]*base[0] + sy*base[1]."""
    da.init(5, 2, 400, True)
    sx, sy = da.Expr("x"), da.Expr("y")
    b0, b1 = da.var(0), da.var(1)
    yield sx, sy, sx + b0 * b0 + sy * b1
    da.clear()


def eval_sda(sv, sx, sy):
    """All full_length() coefficients of sv at (X, Y)."""
    r = da.evaluate(sv, [sx, sy], [X, Y])
    return [r.element(i) for i in range(da.full_length())]


@pytest.mark.parametrize("fn,ref", [
    (da.sqrt, V_SQRT), (da.exp, V_EXP), (da.log, V_LOG),
    (lambda v: da.pow(v, 3), V_POW3), (lambda v: da.pow(v, 0.43), V_POW043),
    (da.erf, V_ERF), (da.sin, V_SIN), (da.cos, V_COS), (da.tan, V_TAN),
    (da.sinh, V_SINH), (da.cosh, V_COSH), (da.tanh, V_TANH),
])
def test_functions(sym, fn, ref):
    sx, sy, f = sym
    assert compare_vectors(ref, eval_sda(fn(f), sx, sy), REF_EPS)


def test_atan(sym):
    sx, sy, _ = sym
    f = sx - 1 + da.var(0) * da.var(0) + sy * da.var(1)
    assert compare_vectors(V_ATAN, eval_sda(da.atan(f), sx, sy), REF_EPS)


