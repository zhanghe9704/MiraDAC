@pytest.fixture
def interop():
    da.init(4, 2, 400, True)
    yield da.var(0), da.var(1)
    da.clear()


def test_promote_round_trip(interop):
    b0, b1 = interop
    n = 1.5 + 2.0 * b0 + 3.0 * b1 + 0.5 * b0 * b1
    back = da.evaluate(da.promote(n), {})
    for i in range(da.full_length()):
        assert abs(n.element(i) - back.element(i)) < EPS


def test_mixed_mul_equals_promoted_mul(interop):
    b0, b1 = interop
    n = 1.0 + 2.0 * b0 + 0.5 * b1
    sx = da.Expr("x")
    s = sx + b0 * b0 + b1
    r1 = da.evaluate(n * s, {sx: da.Expr("1.0")})
    r2 = da.evaluate(da.promote(n) * s, {sx: 1.0})
    for i in range(da.full_length()):
        assert abs(r1.element(i) - r2.element(i)) < EPS


def test_evaluate_with_symbol_map(interop):
    b0, b1 = interop
    sx, sy = da.Expr("px"), da.Expr("py")
    r = da.evaluate(sx + sy * b0 + b1, {sx: 2.0, sy: 3.0})
    assert abs(r.con - 2.0) < EPS


def test_evaluate_vector_form(interop):
    b0, b1 = interop
    sx = da.Expr("qx")
    r = da.evaluate(sx * b0 + 1.0 * b1, [sx], [3.0])
    assert abs(r.element(1) - 3.0) < EPS


def test_mixed_op_same_env_and_cleared_env(interop):
    b0, b1 = interop
    n_main = 1.0 + b0
    s_main = da.Expr("zz") + b1
    n_main * s_main                                  # same env: no error
    da.clear()
    da.init(4, 2, 400, True)
    with pytest.raises(da.EnvError):
        n_main * s_main

